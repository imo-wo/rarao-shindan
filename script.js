let current = 0;
let answers = Array(questions.length).fill(null);

const $ = (id) => document.getElementById(id);
const screens = ['start-screen','quiz-screen','result-screen','answers-screen'];

function showScreen(id) {
  screens.forEach(s => $(s).classList.toggle('is-active', s === id));
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderQuestion() {
  const item = questions[current];
  $('question-number').textContent = `QUESTION ${String(current + 1).padStart(2,'0')} / ${questions.length}`;
  $('progress-bar').style.width = `${((current + 1) / questions.length) * 100}%`;
  $('question-title').textContent = `Q${current + 1}｜${item.title}`;
  $('question-body').innerHTML = item.body;
  $('options').innerHTML = '';

  item.options.forEach(opt => {
    const btn = document.createElement('button');
    btn.className = `option-btn${answers[current] === opt.letter ? ' is-selected' : ''}`;
    btn.type = 'button';
    btn.innerHTML = `<span class="option-letter">${opt.letter}</span><span class="option-text">${opt.text}</span>`;
    btn.addEventListener('click', () => {
      answers[current] = opt.letter;
      renderQuestion();
    });
    $('options').appendChild(btn);
  });

  $('back-btn').disabled = current === 0;
  $('next-btn').disabled = answers[current] === null;
  $('next-btn').textContent = current === questions.length - 1 ? '結果を見る →' : '次へ →';
}

function getStats() {
  let total = 0;
  let zeroCount = 0;
  let tenPlusCount = 0;
  questions.forEach((item, i) => {
    const selected = item.options.find(opt => opt.letter === answers[i]);
    total += selected.score;
    if (selected.score === 0) zeroCount++;
    if (selected.score >= 10) tenPlusCount++;
  });
  return { total, zeroCount, tenPlusCount };
}

function getResult() {
  const { total, zeroCount, tenPlusCount } = getStats();
  const q15Correct = answers[14] === 'E';

  // SECRET判定を通常ENDより先に実施。
  if (total === 160) return results.stage;
  if (total >= 120 && !q15Correct) return results.wrongDate;
  if (zeroCount >= 10 && tenPlusCount <= 2) return results.wrongLive;

  if (total >= 130) return results.front;
  if (total >= 100) return results.arena;
  if (total >= 70) return results.stand;
  if (total >= 40) return results.lobby;
  return results.home;
}

function renderResult() {
  const { total } = getStats();
  const result = getResult();
  $('result-kicker').textContent = result.kicker;
  $('result-icon').textContent = result.icon;
  $('result-title').textContent = result.title;
  $('result-score').textContent = `${total} / 160 POINTS`;
  $('result-copy').innerHTML = result.copy;
  showScreen('result-screen');
}

function renderAnswers() {
  const container = $('answer-list');
  container.innerHTML = '';

  questions.forEach((item, idx) => {
    const selectedLetter = answers[idx];
    const selectedOption = item.options.find(opt => opt.letter === selectedLetter);
    const details = document.createElement('details');
    details.className = 'answer-block';
    if (idx === 0) details.open = true;

    const summary = document.createElement('summary');
    summary.innerHTML = `<h3>Q${idx + 1}｜${item.title}</h3><span class="selected-summary">あなた：${selectedLetter} / ${selectedOption.score}点</span>`;
    details.appendChild(summary);

    const content = document.createElement('div');
    content.className = 'answer-content';
    content.innerHTML = `<div class="intent"><h4>${item.intentTitle}</h4>${item.intentHtml}</div>`;

    item.options.forEach(opt => {
      const feedback = item.feedback.find(x => x.letter === opt.letter);
      const section = document.createElement('section');
      section.className = `feedback-item${selectedLetter === opt.letter ? ' is-user-choice' : ''}`;
      section.innerHTML = `
        <div class="feedback-title">
          <span class="score-badge">${opt.score}点</span>
          <span>｜${opt.letter}「${opt.text}」</span>
          ${selectedLetter === opt.letter ? '<span class="your-choice-chip">あなたの回答</span>' : ''}
        </div>
        ${feedback.html}`;
      content.appendChild(section);
    });

    details.appendChild(content);
    container.appendChild(details);
  });
  showScreen('answers-screen');
}

function resetQuiz() {
  current = 0;
  answers = Array(questions.length).fill(null);
  renderQuestion();
  showScreen('start-screen');
}

$('start-btn').addEventListener('click', () => {
  current = 0;
  renderQuestion();
  showScreen('quiz-screen');
});

$('back-btn').addEventListener('click', () => {
  if (current > 0) { current--; renderQuestion(); }
});

$('next-btn').addEventListener('click', () => {
  if (answers[current] === null) return;
  if (current < questions.length - 1) {
    current++;
    renderQuestion();
    window.scrollTo({ top: 0, behavior: 'smooth' });
  } else {
    renderResult();
  }
});

$('open-answers-btn').addEventListener('click', renderAnswers);
$('back-result-btn').addEventListener('click', () => showScreen('result-screen'));
